-- V1: Initial database schema for IPT Tracker

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_users_role
        CHECK (role IN (
            'ADMIN',
            'STUDENT',
            'INDUSTRIAL_SUPERVISOR',
            'ACADEMIC_SUPERVISOR'
        ))
);

CREATE TABLE organisations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL UNIQUE,
    address VARCHAR(255),
    contact_email VARCHAR(150),
    contact_phone VARCHAR(30),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE placements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    organisation_id BIGINT NOT NULL,
    industrial_supervisor_id BIGINT,
    academic_supervisor_id BIGINT,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_placements_student
        FOREIGN KEY (student_id) REFERENCES users(id),

    CONSTRAINT fk_placements_organisation
        FOREIGN KEY (organisation_id) REFERENCES organisations(id),

    CONSTRAINT fk_placements_industrial_supervisor
        FOREIGN KEY (industrial_supervisor_id) REFERENCES users(id),

    CONSTRAINT fk_placements_academic_supervisor
        FOREIGN KEY (academic_supervisor_id) REFERENCES users(id),

    CONSTRAINT chk_placements_dates
        CHECK (start_date <= end_date),

    CONSTRAINT uq_placements_student_period
        UNIQUE (student_id, start_date, end_date)
);

CREATE TABLE logbook_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placement_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    entry_date DATE NOT NULL,
    title VARCHAR(200) NOT NULL,
    activities TEXT NOT NULL,
    hours_worked INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    supervisor_comment TEXT,
    submitted_at TIMESTAMP,
    reviewed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_logbook_placement
        FOREIGN KEY (placement_id) REFERENCES placements(id),

    CONSTRAINT fk_logbook_student
        FOREIGN KEY (student_id) REFERENCES users(id),

    CONSTRAINT chk_logbook_hours
        CHECK (hours_worked BETWEEN 1 AND 12),

    CONSTRAINT chk_logbook_status
        CHECK (status IN ('DRAFT', 'SUBMITTED', 'APPROVED', 'REJECTED')),

    CONSTRAINT uq_logbook_student_date
        UNIQUE (student_id, entry_date)
);

CREATE TABLE assessments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placement_id BIGINT NOT NULL,
    academic_supervisor_id BIGINT NOT NULL,
    score NUMERIC(5,2),
    feedback TEXT,
    assessed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_assessments_placement
        FOREIGN KEY (placement_id) REFERENCES placements(id),

    CONSTRAINT fk_assessments_academic_supervisor
        FOREIGN KEY (academic_supervisor_id) REFERENCES users(id),

    CONSTRAINT chk_assessments_score
        CHECK (score IS NULL OR score BETWEEN 0 AND 100),

    CONSTRAINT uq_assessments_placement
        UNIQUE (placement_id)
);

CREATE INDEX idx_placements_student
    ON placements(student_id);

CREATE INDEX idx_placements_industrial_supervisor
    ON placements(industrial_supervisor_id);

CREATE INDEX idx_placements_academic_supervisor
    ON placements(academic_supervisor_id);

CREATE INDEX idx_logbook_placement_date
    ON logbook_entries(placement_id, entry_date);

CREATE INDEX idx_logbook_status
    ON logbook_entries(status);

CREATE INDEX idx_assessments_academic_supervisor
    ON assessments(academic_supervisor_id);